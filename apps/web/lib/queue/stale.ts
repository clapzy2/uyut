/**
 * Через сколько считать незаконченную фоновую работу пропавшей.
 *
 * Строки концептов и выгрузок заводятся до того, как задача досчитает, — так человек сразу
 * видит, что дело пошло. Но задача может умереть молча: воркер убит, не уложилась в
 * отведённое время, вовсе не вышла из очереди. Тогда строка навсегда остаётся «в работе»,
 * и на странице вечно висит «ещё считается», а кнопка «Обновить» ничего не меняет.
 *
 * Сроки разные, потому что отсчёт идёт от разного.
 */

/**
 * Концепты: строки создаются внутри самой задачи, поэтому их возраст — это время работы.
 * Задача живёт до десяти минут, пятнадцать берём с запасом.
 */
export const CONCEPT_STALE_AFTER_MS = 15 * 60_000

/**
 * Подбор предметов на рендере идёт отдельной задачей уже после генерации, и его срок
 * отсчитывается от той же строки — значит окно должно вместить обе задачи.
 */
export const OBJECTS_STALE_AFTER_MS = 30 * 60_000

/**
 * Выгрузки: строка заводится до постановки в очередь, поэтому в её возраст входит и ожидание
 * там. Ожидание ничем не ограничено — соседняя генерация занимает тот же пул по десять минут,
 * а раскатка воркера возвращает запуски в очередь. Пятнадцати минут тут мало: живая сборка
 * оказалась бы погашенной, и человек, только что оплативший документ, увидел бы «не удалось».
 */
export const EXPORT_STALE_AFTER_MS = 60 * 60_000

/** Граница, старше которой незаконченная работа считается пропавшей */
export function staleBefore(now: Date, afterMs: number): Date {
  return new Date(now.getTime() - afterMs)
}
