/**
 * Через сколько считать незаконченную фоновую работу пропавшей.
 *
 * Строки концептов и выгрузок заводятся до того, как задача начнёт считать, — так человек
 * сразу видит, что дело пошло. Но задача может умереть молча: воркер убит, не уложилась в
 * отведённое время, вовсе не вышла из очереди. Тогда строка навсегда остаётся «в работе»,
 * и на странице вечно висит «ещё считается», а кнопка «Обновить» ничего не меняет.
 *
 * Пятнадцать минут взяты с запасом: генерация концептов живёт до десяти минут, сборка PDF —
 * до пяти. Всё, что старше, уже точно не досчитается.
 */
export const STALE_AFTER_MS = 15 * 60_000

/** Граница, старше которой незаконченная работа считается пропавшей */
export function staleBefore(now: Date): Date {
  return new Date(now.getTime() - STALE_AFTER_MS)
}
