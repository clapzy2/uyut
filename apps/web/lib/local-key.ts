/**
 * Ключи для списков, которые ещё не сохранены и своего идентификатора не имеют.
 *
 * Намеренно без `crypto.randomUUID()`: в браузере он существует только в защищённом контексте,
 * то есть по HTTPS или на localhost. На сайте, отданном по обычному HTTP, его просто нет, и
 * страница падает целиком при первой отрисовке. Локально это не воспроизводится — localhost
 * считается защищённым, — поэтому ошибка доживает до боевого сервера.
 *
 * Уникальности внутри одной вкладки достаточно: ключи нужны только React, наружу не уходят.
 */
let counter = 0

export function localKey(prefix = 'k'): string {
  counter += 1
  return `${prefix}-${counter}`
}
